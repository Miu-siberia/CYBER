--Câu 1: Viết một Trigger - Tên: tg_NhanVien_insert   
--Yêu cầu: Trigger có chức năng khi thêm mới một Nhân viên, thì kiểm tra trạng thái 
--của nhân viên phải là 1 trong 2 giá trị “Y”, “N” (Y: yes, còn làm việc, N: no, nghỉ 
--việc), nếu không đúng thì thông báo không thêm được và hủy bỏ giao tác thêm này, 
--ngược lại thông báo thêm thành công.
CREATE TRIGGER tg_NhanVien_insert
ON NHANVIEN
INSTEAD OF INSERT
AS
BEGIN
    DECLARE @TRANGTHAI CHAR(1)
    SELECT @TRANGTHAI = i.TRANGTHAI
    FROM inserted i
    IF (@TRANGTHAI NOT IN ('Y', 'N'))
    BEGIN
        RAISERROR('Trạng thái của nhân viên không hợp lệ. Chỉ chấp nhận Y hoặc N.', 16, 1)
        ROLLBACK TRANSACTION
    END
    ELSE
    BEGIN
        INSERT INTO NHANVIEN(MSNV, HOTEN, MAPB, LOAINV, TRANGTHAI)
        SELECT MSNV, HOTEN, MAPB, LOAINV, TRANGTHAI
        FROM inserted
        PRINT 'Thêm nhân viên thành công.'	
    END
END
--Câu 2: Viết một Trigger - Tên: tg_BangChamCong_update - Yêu cầu: Trigger có chức năng khi cập nhật một Bảng chấm công thì kiểm tra số 
--ngày công phải là một con số từ 0 đến 24, nếu không đúng thì thông báo không cập 
--nhật được và hủy bỏ giao tác cập nhật này, ngược lại thông báo cập nhật thành công. 

CREATE TRIGGER tg_BangChamCong_update
ON BANGCHAMCONG
INSTEAD OF UPDATE
AS
BEGIN
    DECLARE @SONGAYCONG INT
    SELECT @SONGAYCONG = i.SONGAYCONG
    FROM inserted i
    IF (@SONGAYCONG > 0 OR @SONGAYCONG < 24)
    BEGIN
        RAISERROR('Số ngày công không hợp lệ. Vui lòng nhập giá trị từ 0 đến 24.', 16, 1)
        ROLLBACK TRANSACTION
    END
    ELSE
    BEGIN
        UPDATE BANGCHAMCONG
        SET SONGAYCONG = i.SONGAYCONG
        FROM inserted i
        WHERE BANGCHAMCONG.MSNV = i.MSNV AND BANGCHAMCONG.THANG = i.THANG AND BANGCHAMCONG.NAM = i.NAM and BANGCHAMCONG.SONGAYCONG=i.SONGAYCONG
        
        PRINT 'Cập nhật bảng chấm công thành công.'	
    END
END
--Câu 3: Viết một Trigger - Tên: tg_LuongThang_insert - Yêu cầu: Trigger có chức năng khi thêm mới một Lương tháng thì kiểm tra số tiền trả 
--tháng tạm ứng của nhân viên đó có bằng với tạm ứng trong Lương tháng hay không, 
--nếu bằng thì cập nhật lại số tiền còn tạm ứng (SOTIENCONTU) trong bảng Tạm 
--ứng, SOTIENCONTU= SOTIENCONTU (hiện tại) – TAMUNG (trong Lương 
--tháng), nếu không bằng thì thông báo lỗi và huỷ bỏ giao tác thêm, ngược lại thông 
--báoo thêm thành công. 
CREATE TRIGGER tg_LuongThang_insert
ON LUONGTHANG
INSTEAD OF INSERT
AS
BEGIN
    DECLARE @TAMUNG INT
    DECLARE @SOTIENCONTU INT
    DECLARE @MSNV INT
    SELECT @TAMUNG = i.TAMUNG, @MSNV = i.MSNV
    FROM inserted i
    
    SELECT @SOTIENCONTU = t.SOTIENCONTU
    FROM TAMUNG t
    WHERE t.MSNV = @MSNV
    IF (@TAMUNG != @SOTIENCONTU)
    BEGIN
        RAISERROR('Tạm ứng không khớp với số tiền còn lại. Không thể thêm lương tháng.', 16, 1)
        ROLLBACK TRANSACTION
    END
    ELSE
    BEGIN
       
        INSERT INTO LUONGTHANG (MSNV, THANG, NAM, LUONGCB, TAMUNG, PHUCAP, TONGLUONG)
        SELECT MSNV, THANG, NAM, LUONGCB, TAMUNG, PHUCAP, TONGLUONG
        FROM inserted
        
        UPDATE TAMUNG
        SET SOTIENCONTU = SOTIENCONTU - @TAMUNG
        WHERE MSNV = @MSNV
        
        PRINT 'Thêm lương tháng thành công và cập nhật số tạm ứng.'	
    END
END

